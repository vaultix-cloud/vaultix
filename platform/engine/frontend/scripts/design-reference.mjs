// Writes the component reference in platform/engine/DESIGN.md from the design-system stories, so
// the document and Storybook cannot disagree: each entry is the story's title, its documented
// behaviour and keyboard model, and its stories. `--check` fails when DESIGN.md is out of date.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const frontend = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const system = resolve(frontend, "src/design-system");
const designDoc = resolve(frontend, "../DESIGN.md");
const START = "<!-- reference:start (generated by frontend/scripts/design-reference.mjs) -->";
const END = "<!-- reference:end -->";

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

const unescape = (text) => text.replace(/\\(["'`\\])/g, "$1");

const entries = walk(system)
  .filter((file) => file.endsWith(".stories.tsx"))
  .map((file) => {
    const text = readFileSync(file, "utf8");
    const title = text.match(/title:\s*"([^"]+)"/)?.[1];
    const description = text.match(/component:\s*(["'`])((?:\\.|(?!\1)[\s\S])*)\1/)?.[2];
    const stories = [...text.matchAll(/export const (\w+): Story/g)].map((match) => match[1]);
    if (!title || !description) {
      throw new Error(`${relative(frontend, file)} needs a title and a docs.description.component`);
    }
    return {
      title,
      // The Storybook path without the "Design System" root, e.g. "Primitives / Button".
      name: title.split("/").slice(1).join(" / "),
      path: relative(resolve(frontend, ".."), file).replaceAll("\\", "/"),
      description: unescape(description),
      stories
    };
  })
  .sort((a, b) => a.title.localeCompare(b.title));

const section = [
  START,
  "",
  ...entries.flatMap((entry) => [
    `### ${entry.name}`,
    "",
    entry.description,
    "",
    `Stories: ${entry.stories.join(", ")} · [source](${entry.path})`,
    ""
  ]),
  END
].join("\n");

const current = readFileSync(designDoc, "utf8").replace(/\r\n/g, "\n");
const begin = current.indexOf(START);
const finish = current.indexOf(END);
if (begin < 0 || finish < begin) throw new Error(`DESIGN.md needs the reference markers`);
const next = current.slice(0, begin) + section + current.slice(finish + END.length);

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("DESIGN.md's reference is out of date; run node scripts/design-reference.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(designDoc, next);
}
console.log(JSON.stringify({ components: entries.length, mode: process.argv.includes("--check") ? "check" : "write" }));
